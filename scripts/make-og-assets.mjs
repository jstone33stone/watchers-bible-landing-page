/* ── WOFF → sfnt, verbatim from the web app's functions/api/_lib/woff.js ── */

function woffToTtf(buf) {
  const u8 = buf instanceof Uint8Array ? buf : new Uint8Array(buf);
  const sig = String.fromCharCode(u8[0], u8[1], u8[2], u8[3]);
  if (sig !== "wOFF") return u8;

  const dv = new DataView(u8.buffer, u8.byteOffset, u8.byteLength);
  const numTables = dv.getUint16(12);

  const tables = [];
  for (let i = 0; i < numTables; i += 1) {
    const o = 44 + i * 20;
    const tag = String.fromCharCode(u8[o], u8[o + 1], u8[o + 2], u8[o + 3]);
    const offset = dv.getUint32(o + 4);
    const compLength = dv.getUint32(o + 8);
    const origLength = dv.getUint32(o + 12);
    const checksum = dv.getUint32(o + 16);
    const raw = u8.subarray(offset, offset + compLength);
    let data;
    if (compLength < origLength) {
      data = inflateSync(raw);
      if (data.length !== origLength) {
        throw new Error(`woff: table ${tag} inflated to ${data.length}, expected ${origLength}`);
      }
    } else {
      data = raw.slice();
    }
    tables.push({ tag, data, checksum });
  }

  tables.sort((a, b) => (a.tag < b.tag ? -1 : a.tag > b.tag ? 1 : 0));
  const entrySelector = Math.floor(Math.log2(numTables));
  const searchRange = 16 * 2 ** entrySelector;
  const rangeShift = numTables * 16 - searchRange;
  const headerLen = 12 + 16 * numTables;
  const padOf = (len) => (4 - (len % 4)) % 4;
  const total =
    headerLen + tables.reduce((n, t) => n + t.data.length + padOf(t.data.length), 0);

  const out = new Uint8Array(total);
  const odv = new DataView(out.buffer);
  odv.setUint32(0, 0x00010000);
  odv.setUint16(4, numTables);
  odv.setUint16(6, searchRange);
  odv.setUint16(8, entrySelector);
  odv.setUint16(10, rangeShift);

  let writeOffset = headerLen;
  for (let i = 0; i < numTables; i += 1) {
    const t = tables[i];
    const rec = 12 + i * 16;
    for (let c = 0; c < 4; c += 1) out[rec + c] = t.tag.charCodeAt(c);
    odv.setUint32(rec + 4, t.checksum);
    odv.setUint32(rec + 8, writeOffset);
    odv.setUint32(rec + 12, t.data.length);
    out.set(t.data, writeOffset);
    writeOffset += t.data.length + padOf(t.data.length);
  }
  return out;
}

const b64 = (u8) => Buffer.from(u8).toString("base64");

/* ── fonts-ttf.js ────────────────────────────────────────────────────────── */

const fonts = await import(pathToFileURL(join(ROOT, "functions", "_og", "fonts.js")).href);
const faces = [
  ["INTER_700", fonts.INTER_700, "inter700"],
  ["LITERATA_500", fonts.LITERATA_500, "literata500"],
  ["LITERATA_400_ITALIC", fonts.LITERATA_400_ITALIC, "literata400Italic"],
];

let fontsOut = `/**
 * Precomputed sfnt (TTF) faces for resvg's fontdb — generated by
 * scripts/make-og-assets.mjs from _og/fonts.js's WOFF payloads (resvg only
 * paints raw sfnt; a WOFF buffer loads as nothing and every <text>
 * silently disappears). Shipping the conversion's output keeps the worker
 * free of node:zlib. Only the painted faces ride here — opentype measures
 * straight from the WOFF in fonts.js.
 */
`;

for (const [name, payload] of faces) {
  const ttf = woffToTtf(Buffer.from(payload, "base64"));
  fontsOut += `export const ${name}_TTF = "${b64(ttf)}";\n`;
  console.log(name, "woff", payload.length, "→ ttf", b64(ttf).length, "b64 chars");
}
writeFileSync(join(ROOT, "functions", "_og", "fonts-ttf.js"), fontsOut);

